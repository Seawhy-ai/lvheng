const {chromium}=require("playwright");
const assert=require("node:assert/strict");
(async()=>{
  const browser=await chromium.launch({headless:true,...(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH}:{}),args:["--no-sandbox"]});
  const page=await browser.newPage({viewport:{width:1440,height:1000},serviceWorkers:"block"});
  const errors=[];page.on("pageerror",e=>errors.push(e.message));
  page.on("dialog",d=>d.accept());
  await page.addInitScript(()=>localStorage.setItem("lvheng_classroom_api_v1",""));
  await page.goto("http://127.0.0.1:8765/classroom.html?preview=local");
  await page.click("#teacherEntry");await page.click("#newTask");
  await page.fill("#studioTitle","测试：证据识别任务");
  await page.fill("#studioDue","2099-01-01T12:00");
  await page.click('[data-step="2"]');
  await page.fill("#studioPrompt","请选择可以证明兼职出勤情况的证据");
  await page.fill("#studioOption0","完整考勤和排班记录");
  await page.selectOption("#studioAnswer","0");
  await page.click("#studioSave");
  await page.waitForFunction(()=>document.querySelector(".studio-save-state")?.textContent==="草稿已保存");
  await page.screenshot({path:"/tmp/lvheng-studio-desktop.png",fullPage:true});
  await page.click("#modalClose");
  const row=page.locator(".studio-task-row").filter({hasText:"测试：证据识别任务"});
  await row.locator("[data-manage]").click();
  await page.click('[data-step="2"]');
  assert.equal(await page.inputValue("#studioPrompt"),"请选择可以证明兼职出勤情况的证据");
  await page.click("#studioPreview");
  assert.equal(await page.locator(".studio-paper section").count(),5);
  assert.equal(await page.locator(".studio-paper").getByText("正确答案",{exact:true}).count(),0);
  await page.click("#studioPublish");
  assert.match(await page.textContent("#toast"),/审核/);
  await page.check("#studioReviewed");
  await page.click("#studioPublish");
  await page.waitForFunction(()=>document.getElementById("modal").hidden);
  await row.locator("[data-manage]").click();
  await page.waitForSelector(".studio-manage");
  await page.click("#studioCloseTask");
  await page.waitForFunction(()=>!document.getElementById("studioCloseTask"));
  await page.click("#modalClose");
  assert.match(await row.textContent(),/已结束/);
  await page.setViewportSize({width:390,height:844});
  await page.click("#newTask");
  await page.click('[data-step="1"]');
  await page.screenshot({path:"/tmp/lvheng-studio-mobile.png",fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth),false);
  assert.ok(await page.locator(".cm-modal-card").evaluate(el=>el.getBoundingClientRect().right<=innerWidth));
  assert.deepEqual(errors,[]);
  const online=await browser.newPage({viewport:{width:1200,height:900},serviceWorkers:"block"});
  online.on("pageerror",e=>errors.push(e.message));
  await online.addInitScript(()=>{
    localStorage.setItem("lvheng_classroom_api_v1","https://worker.test");
    localStorage.setItem("lvheng_classroom_session_v1",JSON.stringify({user:{id:"teacher-test",role:"teacher",name:"测试教师"},token:"test-only"}));
  });
  let regenerated=0;
  await online.route("https://worker.test/**",async route=>{
    const path=new URL(route.request().url()).pathname;
    let body={};
    if(path==="/health")body={ok:true,database:true,taskStudio:1};
    if(path==="/api/classes")body={classes:[{id:"class-test",name:"测试班",code:"ABC123"}]};
    if(path==="/api/tasks")body={tasks:[]};
    if(path.endsWith("/dashboard"))body={stats:{students:0,publishedTasks:0,submissions:0,average:null,abilities:{}},recent:[]};
    if(path==="/api/agent/question-draft"){
      const input=route.request().postDataJSON();
      assert.equal(input.index,2);
      body={question:{...input.content.questions[2],prompt:"重写后的证据意识问题"},source:"deepseek"};
      regenerated++;
    }
    await route.fulfill({json:body});
  });
  await online.goto("http://127.0.0.1:8765/classroom.html");
  await online.click("#newTask");
  await online.click('[data-step="0"]');
  const untouched=await online.inputValue("#studioPrompt");
  await online.click('[data-step="2"]');
  await online.click("#studioRegenerate");
  await online.waitForFunction(()=>document.getElementById("studioPrompt")?.value==="重写后的证据意识问题");
  await online.click('[data-step="0"]');
  assert.equal(await online.inputValue("#studioPrompt"),untouched);
  assert.equal(regenerated,1);
  assert.deepEqual(errors,[]);
  await browser.close();
  console.log("Studio desktop/mobile edit, persistence, preview, review, publish, close and isolated AI regeneration passed");
})().catch(e=>{console.error(e);process.exit(1)});
